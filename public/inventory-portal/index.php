<?php
declare(strict_types=1);

require_once __DIR__ . '/app/bootstrap.php';
require_once __DIR__ . '/app/database.php';
require_once __DIR__ . '/app/auth.php';
require_once __DIR__ . '/app/permissions.php';

function inventory_render_login(?string $error = null): never
{
    $csrf = inv_csrf_token();
    $base = inv_base_path();
    ?><!doctype html>
    <html lang="en"><head>
        <meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
        <title>Inventory &amp; Profit Management</title>
        <link rel="stylesheet" href="<?= inv_e(inv_asset('assets/css/portal.css')) ?>">
        <link rel="stylesheet" href="<?= inv_e(inv_asset('assets/css/modules.css')) ?>">
    </head><body class="login-page">
        <main class="login-card">
            <div class="brand-mark" aria-hidden="true">EE</div>
            <p class="eyebrow">RESTAURANT OPERATIONS</p>
            <h1>Inventory &amp; Profit</h1>
            <p class="muted">Use your Manager email and the separate Inventory Portal password generated by your SaaS Owner.</p>
            <?php if ($error): ?><p class="notice notice-error" role="alert"><?= inv_e($error) ?></p><?php endif; ?>
            <form method="post" action="<?= inv_e($base) ?>/login.php" class="stack-form" autocomplete="on">
                <input type="hidden" name="action" value="login">
                <input type="hidden" name="csrf" value="<?= inv_e($csrf) ?>">
                <label>Manager email address<input type="email" name="email" maxlength="190" autocomplete="username" required></label>
                <label>Inventory Portal password<input type="password" name="password" maxlength="72" autocomplete="current-password" required></label>
                <button class="button button-primary" type="submit">Sign in</button>
            </form>
            <p class="login-note">This password is separate from your regular Restaurant SaaS password. Ask your SaaS Owner to enable access or generate a new portal password.</p>
        </main>
        <footer class="software-credit">Software Development by <a href="https://www.energeticedge.lk/" target="_blank" rel="noopener noreferrer">Energetic Edge (Pvt) Ltd</a></footer>
    </body></html><?php
    exit;
}

try {
    $db = inventory_database();
    if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST' && ($_POST['action'] ?? '') === 'login') {
        try {
            inv_require_csrf();
            $email = (string)($_POST['email'] ?? '');
            $password = (string)($_POST['password'] ?? '');
            if (strlen($email) > 190 || strlen($password) > 72 || !inventory_login($db, $email, $password)) {
                inventory_render_login('Email, password, or Inventory Portal access is incorrect.');
            }
            inv_redirect('dashboard');
        } catch (RuntimeException $exception) {
            inventory_render_login($exception->getMessage());
        }
    }

    if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST' && ($_POST['action'] ?? '') === 'logout') {
        inv_require_csrf();
        inventory_forget_session();
        header('Location: ' . inv_base_path() . '/login.php', true, 303);
        exit;
    }

    $context = inventory_context($db);
    if (!$context) {
        inventory_render_login();
    }

    if (($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST') {
        require_once __DIR__ . '/app/actions.php';
        inventory_handle_action($db, $context);
    }

    $page = preg_replace('/[^a-z-]/', '', strtolower((string)($_GET['page'] ?? 'dashboard'))) ?: 'dashboard';
    $pages = [
        'dashboard' => 'Dashboard',
        'materials' => 'Raw Materials',
        'recipes' => 'Recipes',
        'purchases' => 'Purchases',
        'suppliers' => 'Suppliers',
        'stock' => 'Stock',
        'wastage' => 'Wastage',
        'stock-count' => 'Stock Count',
        'food-costing' => 'Food Costing',
        'profit-reports' => 'Profit Reports',
        'automation-readiness' => 'Automation Readiness',
        'settings' => 'Settings',
    ];
    if (!array_key_exists($page, $pages)) {
        $page = 'dashboard';
    }

    $flash = inv_flash();
    $csrf = inv_csrf_token();
    ?><!doctype html>
    <html lang="en"><head>
        <meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
        <title><?= inv_e($pages[$page]) ?> · Inventory &amp; Profit</title>
        <link rel="stylesheet" href="<?= inv_e(inv_asset('assets/css/portal.css')) ?>">
        <link rel="stylesheet" href="<?= inv_e(inv_asset('assets/css/modules.css')) ?>">
        <link rel="stylesheet" href="<?= inv_e(inv_asset('assets/css/recipes.css')) ?>">
        <link rel="stylesheet" href="<?= inv_e(inv_asset('assets/css/reports.css')) ?>">
    </head><body>
        <div class="app-shell">
            <aside class="sidebar" id="portal-sidebar">
                <a class="brand-lockup" href="<?= inv_e(inv_route('dashboard')) ?>"><span class="brand-mark">EE</span><span><strong>Inventory</strong><small>Profit Management</small></span></a>
                <div class="tenant-label"><span class="eyebrow">RESTAURANT</span><strong><?= inv_e($context['restaurant_name']) ?></strong><small><?= inv_e(str_replace('_', ' ', $context['portal_role'])) ?></small></div>
                <nav class="primary-nav" aria-label="Inventory navigation">
                    <?php foreach ($pages as $key => $label): ?>
                        <a class="nav-link<?= $page === $key ? ' is-active' : '' ?>" href="<?= inv_e(inv_route($key)) ?>"<?= $page === $key ? ' aria-current="page"' : '' ?>>
                            <span class="nav-icon" aria-hidden="true"><?= inv_e(match ($key) { 'dashboard' => '⌂', 'materials' => '◈', 'recipes' => '≋', 'purchases' => '▤', 'suppliers' => '♧', 'stock' => '▦', 'wastage' => '↘', 'stock-count' => '☷', 'food-costing' => '◷', 'profit-reports' => '▥', default => '⚙' }) ?></span><span><?= inv_e($label) ?></span>
                        </a>
                    <?php endforeach; ?>
                </nav>
                <div class="sidebar-bottom"><span class="sidebar-user"><?= inv_e($context['user_name']) ?></span><form method="post" action="<?= inv_e(inv_base_path()) ?>/logout.php"><input type="hidden" name="csrf" value="<?= inv_e($csrf) ?>"><button class="button button-quiet" type="submit">Sign out</button></form></div>
            </aside>
            <div class="mobile-scrim" data-close-menu></div>
            <main class="main-area">
                <header class="topbar"><button class="mobile-menu-button" type="button" aria-label="Open navigation" aria-expanded="false" aria-controls="portal-sidebar" data-menu-toggle>☰</button><div><span class="eyebrow">INVENTORY WORKSPACE</span><h1><?= inv_e($pages[$page]) ?></h1></div><div class="topbar-user"><span class="avatar"><?= inv_e(mb_strtoupper(mb_substr((string)$context['restaurant_name'], 0, 1))) ?></span><span><strong><?= inv_e($context['restaurant_name']) ?></strong><small><?= inv_e($context['user_name']) ?></small></span></div></header>
                <section class="content-area">
                    <?php if ($flash): ?><div class="notice notice-<?= inv_e($flash['type']) ?>" role="status"><?= inv_e($flash['message']) ?></div><?php endif; ?>
                    <?php if ($page === 'dashboard'): ?>
                        <?php require_once __DIR__ . '/app/inventory-service.php'; ?>
                        <?php require __DIR__ . '/pages/dashboard.php'; ?>
                    <?php elseif (in_array($page, ['materials', 'suppliers', 'purchases', 'stock'], true)): ?>
                        <?php require __DIR__ . '/pages/' . $page . '.php'; ?>
                    <?php elseif (in_array($page, ['recipes', 'food-costing'], true)): ?>
                        <?php require_once __DIR__ . '/app/recipes-service.php'; ?>
                        <?php require __DIR__ . '/pages/' . $page . '.php'; ?>
                    <?php elseif ($page === 'wastage'): ?>
                        <?php require_once __DIR__ . '/app/kot-service.php'; ?>
                        <?php require __DIR__ . '/pages/wastage.php'; ?>
                    <?php elseif ($page === 'stock-count'): ?>
                        <?php require_once __DIR__ . '/app/stock-count-service.php'; ?>
                        <?php require __DIR__ . '/pages/stock-count.php'; ?>
                    <?php elseif ($page === 'profit-reports'): ?>
                        <?php require_once __DIR__ . '/app/report-service.php'; ?>
                        <?php require __DIR__ . '/pages/profit-reports.php'; ?>
                    <?php elseif ($page === 'automation-readiness'): ?>
                        <?php require __DIR__ . '/pages/automation-readiness.php'; ?>
                    <?php else: ?>
                        <?php require __DIR__ . '/pages/coming-soon.php'; ?>
                    <?php endif; ?>
                </section>
                <footer class="software-credit">Software Development by <a href="https://www.energeticedge.lk/" target="_blank" rel="noopener noreferrer">Energetic Edge (Pvt) Ltd</a></footer>
            </main>
        </div>
        <script src="<?= inv_e(inv_asset('assets/js/portal.js')) ?>" defer></script>
    </body></html><?php
} catch (Throwable $exception) {
    error_log('[inventory-portal] ' . $exception->getMessage());
    http_response_code(503);
    ?><!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Inventory Portal unavailable</title><link rel="stylesheet" href="<?= inv_e(inv_asset('assets/css/portal.css')) ?>"><link rel="stylesheet" href="<?= inv_e(inv_asset('assets/css/modules.css')) ?>"></head><body class="login-page"><main class="login-card"><p class="eyebrow">SETUP REQUIRED</p><h1>Inventory Portal is not ready yet</h1><p class="muted">Check the installation instructions and database connection, then run the portal migrations. Existing Restaurant SaaS data has not been changed.</p><a class="button button-primary" href="<?= inv_e(inv_base_path()) ?>/login.php">Try again</a></main><footer class="software-credit">Software Development by <a href="https://www.energeticedge.lk/" target="_blank" rel="noopener noreferrer">Energetic Edge (Pvt) Ltd</a></footer></body></html><?php
}
